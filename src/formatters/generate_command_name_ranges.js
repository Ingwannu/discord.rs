// Regenerates src/formatters/command_name_ranges.rs:
//   node src/formatters/generate_command_name_ranges.js > src/formatters/command_name_ranges.rs
// The class is copied from discord.js `cleanContent` (packages/discord.js/
// src/util/Util.js); the table is whatever this Node's regex engine accepts.
const re = /[-_\p{L}\p{N}\p{sc=Deva}\p{sc=Thai} ]/u;
const ranges = [];
let start = -1;
for (let cp = 0; cp <= 0x110000; cp++) {
  const ok = cp <= 0x10ffff && !(cp >= 0xd800 && cp <= 0xdfff) && re.test(String.fromCodePoint(cp));
  if (ok && start < 0) start = cp;
  if (!ok && start >= 0) {
    ranges.push([start, cp - 1]);
    start = -1;
  }
}
const hex = (cp) => '0x' + cp.toString(16).toUpperCase().padStart(4, '0');
const lines = [];
for (let i = 0; i < ranges.length; i += 4) {
  lines.push('    ' + ranges.slice(i, i + 4).map(([lo, hi]) => `(${hex(lo)}, ${hex(hi)}),`).join(' '));
}
process.stdout.write(`//! Code points matched by discord.js \`cleanContent\`'s command-name class
//! \`[-_\\p{L}\\p{N}\\p{sc=Deva}\\p{sc=Thai} ]\`, as inclusive ranges.
//!
//! Generated by \`generate_command_name_ranges.js\` on Node ${process.version}
//! (Unicode ${process.versions.unicode}, ICU ${process.versions.icu}). Do not edit by hand.

/// Unicode version the table was generated from (checked by the tests).
#[cfg(test)]
pub(super) const UNICODE_VERSION: &str = "${process.versions.unicode}";

/// Sorted, non-overlapping, non-adjacent inclusive ranges.
#[rustfmt::skip]
pub(super) const RANGES: &[(u32, u32)] = &[
${lines.join('\n')}
];
`);
